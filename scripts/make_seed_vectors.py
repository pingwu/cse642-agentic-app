"""Instructor tool: rebuild supabase/seed_vectors.sql from data/reference.

Chunks every file in data/reference (about 800 characters, 100 overlap), embeds the
chunks with the pinned model, and writes a self-contained SQL file. Students without
an embedding key load that file and rejoin the lab.

    OPENROUTER_API_KEY=... uv run scripts/make_seed_vectors.py
    uv run scripts/make_seed_vectors.py --dry-run     # chunk only, no key, no network

The model and dimension must match backend/.env.example. Change both together.
"""

import json
import os
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
MODEL = "openai/text-embedding-3-small"
DIM = 1536
CHUNK, OVERLAP = 800, 100


def chunk(text: str) -> list[str]:
    out, start = [], 0
    while start < len(text):
        out.append(text[start : start + CHUNK].strip())
        if start + CHUNK >= len(text):
            break
        start += CHUNK - OVERLAP
    return [c for c in out if c]


def source_type(path: Path) -> str:
    return path.stem.split("-")[0]


def sql_text(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    dry = "--dry-run" in sys.argv
    rows = []
    for path in sorted((ROOT / "data" / "reference").glob("*.md")):
        for i, c in enumerate(chunk(path.read_text(encoding="utf-8"))):
            rows.append((c, source_type(path), {"file": path.name, "chunk": i}))
    counts: dict[str, int] = {}
    for _, st, _ in rows:
        counts[st] = counts.get(st, 0) + 1
    print(f"{len(rows)} chunks: {counts}")
    if dry:
        return

    key = os.environ.get("OPENROUTER_API_KEY")
    if not key:
        sys.exit("Set OPENROUTER_API_KEY, or use --dry-run.")
    r = httpx.post(
        "https://openrouter.ai/api/v1/embeddings",
        headers={"Authorization": f"Bearer {key}"},
        json={"model": MODEL, "input": [c for c, _, _ in rows]},
        timeout=120,
    )
    r.raise_for_status()
    vectors = [d["embedding"] for d in sorted(r.json()["data"], key=lambda d: d["index"])]
    assert len(vectors) == len(rows) and all(len(v) == DIM for v in vectors), "dimension mismatch"

    lines = [
        f"-- Pre-computed embeddings for data/reference. Model {MODEL}, {DIM} dimensions.",
        "-- Generated by scripts/make_seed_vectors.py. Safe to run twice: it replaces the seed rows.",
        "create extension if not exists vector;",
        "create table if not exists public.knowledge_chunks (",
        "  id bigint generated always as identity primary key,",
        "  content text not null,",
        f"  embedding vector({DIM}) not null,",
        "  source_type text not null,",
        "  metadata jsonb not null default '{}'::jsonb",
        ");",
        "create index if not exists knowledge_chunks_embedding_idx on public.knowledge_chunks using hnsw (embedding vector_cosine_ops);",
        "create index if not exists knowledge_chunks_source_idx on public.knowledge_chunks (source_type);",
        "delete from public.knowledge_chunks where metadata->>'seed' = 'true';",
    ]
    for (c, st, meta), v in zip(rows, vectors):
        meta = {**meta, "seed": "true"}
        vec = "[" + ",".join(f"{x:.6f}" for x in v) + "]"
        lines.append(
            "insert into public.knowledge_chunks (content, embedding, source_type, metadata) values "
            f"({sql_text(c)}, '{vec}', {sql_text(st)}, {sql_text(json.dumps(meta))}::jsonb);"
        )
    out = ROOT / "supabase" / "seed_vectors.sql"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
